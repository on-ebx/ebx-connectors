#!/usr/bin/env python3
"""Generate the end-to-end connector operationalization matrix."""
import argparse, json, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def render(coverage, policy):
    catalog = sorted(coverage["catalog"], key=lambda value: value["connectorType"])
    types = {value["connectorType"] for value in catalog}
    overrides = policy["overrides"]
    unknown = sorted(set(overrides) - types)
    if unknown: raise ValueError("unknown connector overrides: " + ", ".join(unknown))
    allowed = set(policy["allowedStatuses"])
    rows=[]
    for item in catalog:
        connector=item["connectorType"]; value=overrides.get(connector,{})
        status=value.get("status",policy["defaultStatus"])
        if status not in allowed: raise ValueError("invalid status for "+connector+": "+status)
        rows.append((connector,status,value.get("evidence","—"),value.get("nextAction","Create an acceptance charter and disposable fixture.")))
    counts=Counter(row[1] for row in rows)
    lines=["# Connector end-to-end operational readiness","","<!-- Generated by tools/generate_operational_readiness.py; do not edit by hand. -->","",
      "A connector is `ACCEPTED` only after the existing EBX record completes the entire governed lifecycle against an approved external fixture and retains read-back, monitoring, recovery, and restoration evidence.","",
      "Required lifecycle: `"+" → ".join(policy["requiredStages"])+"`.","",
      "Catalog total: **%d**. Status distribution: %s."%(len(rows),", ".join("%s: %d"%(key,counts[key]) for key in sorted(counts))),"",
      "| Connector type | Operational status | Evidence | Next action |","|---|---|---|---|"]
    lines += ["| %s | %s | %s | %s |"%row for row in rows]
    return "\n".join(lines)+"\n"

def main():
    parser=argparse.ArgumentParser(); parser.add_argument("--check",action="store_true")
    parser.add_argument("--coverage",default=str(ROOT/"connector-coverage.yaml")); parser.add_argument("--policy",default=str(ROOT/"operational-readiness.json")); parser.add_argument("--output",default=str(ROOT/"docs/CONNECTOR-OPERATIONAL-READINESS.md")); args=parser.parse_args()
    rendered=render(json.loads(Path(args.coverage).read_text()),json.loads(Path(args.policy).read_text())); output=Path(args.output)
    if args.check:
        if not output.is_file() or output.read_text()!=rendered: print("STALE: regenerate "+str(output),file=sys.stderr); return 1
        print("PASS: operational readiness matrix is current"); return 0
    output.write_text(rendered); print("WROTE: "+str(output)); return 0
if __name__=="__main__": raise SystemExit(main())
