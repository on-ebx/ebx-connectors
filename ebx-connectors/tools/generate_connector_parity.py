#!/usr/bin/env python3
"""Generate the connector catalog/capability parity report.

The coverage manifest deliberately uses JSON syntax (valid YAML 1.2), so this
tool has no third-party dependency.  Use ``--check`` in CI to reject a stale
generated report.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping, Sequence

DEFAULT_MANIFEST = "connector-coverage.yaml"
DEFAULT_OUTPUT = "docs/CONNECTOR-CAPABILITY-PARITY.md"


def _cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def _distribution(values: Iterable[str]) -> str:
    counts = Counter(values)
    return ", ".join(f"{name}: {counts[name]}" for name in sorted(counts))


def _table(headers: Sequence[str], rows: Iterable[Sequence[Any]]) -> List[str]:
    rendered = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    rendered.extend("| " + " | ".join(_cell(value) for value in row) + " |" for row in rows)
    return rendered


def render(document: Mapping[str, Any], manifest_bytes: bytes) -> str:
    catalog = list(document.get("catalog", []))
    targets = list(document.get("externalTargets", []))
    if not catalog or not targets:
        raise ValueError("manifest must contain non-empty catalog and externalTargets arrays")

    catalog.sort(key=lambda item: (str(item.get("connectorType", "")), str(item.get("id", ""))))
    targets.sort(key=lambda item: (str(item.get("sourceSection", "")), str(item.get("sourceName", "")), str(item.get("id", ""))))
    catalog_types = {str(item["connectorType"]) for item in catalog}
    mapped_types = {
        str(item.get("coveredBy"))
        for item in targets
        if item.get("coveredBy") in catalog_types
    }
    unresolved = [item for item in targets if item.get("coverageStatus") not in ("COVERED", "N_A")]
    orphaned = [item for item in catalog if item["connectorType"] not in mapped_types]

    by_section: Dict[str, List[Mapping[str, Any]]] = defaultdict(list)
    for item in targets:
        by_section[str(item["sourceSection"])].append(item)

    lines = [
        "# Connector catalog and capability parity",
        "",
        "<!-- Generated by tools/generate_connector_parity.py; do not edit by hand. -->",
        "",
        f"Manifest baseline: `{document.get('baselineDate', 'unspecified')}`",
        f"Manifest SHA-256: `{hashlib.sha256(manifest_bytes).hexdigest()}`",
        "",
        "## Summary",
        "",
        f"- Catalog connector types: **{len(catalog)}**",
        f"- Capability baseline items: **{len(targets)}**",
        f"- Capability coverage: **{len(targets) - len(unresolved)} resolved**, **{len(unresolved)} open**",
        f"- Catalog types referenced by capability items: **{len(mapped_types)}**",
        f"- Catalog types without a direct capability mapping: **{len(orphaned)}**",
        f"- Catalog workflow: {_distribution(str(item['workflowStatus']) for item in catalog)}",
        f"- Capability coverage status: {_distribution(str(item['coverageStatus']) for item in targets)}",
        "",
        "A resolved capability is `COVERED` or intentionally dispositioned `N_A`. A catalog type can be valid without a direct capability mapping because the baseline groups some products and shared capabilities.",
        "",
        "## Capability sections",
        "",
    ]
    section_rows = []
    for section in sorted(by_section):
        items = by_section[section]
        open_count = sum(item.get("coverageStatus") not in ("COVERED", "N_A") for item in items)
        section_rows.append((section, len(items), len(items) - open_count, open_count, _distribution(str(item["coverageStatus"]) for item in items)))
    lines.extend(_table(("Section", "Items", "Resolved", "Open", "Coverage status"), section_rows))

    lines.extend(["", "## Open capability items", ""])
    if unresolved:
        lines.extend(_table(
            ("ID", "Section", "Capability", "Coverage", "Workflow", "Covered by"),
            ((item["id"], item["sourceSection"], item.get("canonicalName", item["sourceName"]), item["coverageStatus"], item["workflowStatus"], item.get("coveredBy", "—")) for item in unresolved),
        ))
    else:
        lines.append("None.")

    lines.extend(["", "## Catalog types without a direct capability mapping", ""])
    if orphaned:
        lines.extend(_table(
            ("Connector type", "Registration", "Workflow", "Implementation"),
            ((item["connectorType"], item["registrationMode"], item["workflowStatus"], item["implementation"]) for item in orphaned),
        ))
    else:
        lines.append("None.")

    lines.extend(["", "## Enforcement", "", "Regenerate after changing the manifest:", "", "```sh", "python3 tools/generate_connector_parity.py", "```", "", "Fail when the checked-in report is stale:", "", "```sh", "python3 tools/generate_connector_parity.py --check", "```", ""])
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", default=DEFAULT_MANIFEST)
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail if the output is absent or stale")
    parser.add_argument("--stdout", action="store_true", help="print generated Markdown without writing it")
    args = parser.parse_args(argv)

    manifest_path = Path(args.manifest)
    manifest_bytes = manifest_path.read_bytes()
    generated = render(json.loads(manifest_bytes.decode("utf-8")), manifest_bytes)
    output_path = Path(args.output)

    if args.stdout:
        sys.stdout.write(generated)
        return 0
    if args.check:
        if not output_path.is_file() or output_path.read_text(encoding="utf-8") != generated:
            print(f"STALE: regenerate {output_path} from {manifest_path}", file=sys.stderr)
            return 1
        print(f"PASS: {output_path} is current")
        return 0

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(generated, encoding="utf-8")
    print(f"WROTE: {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
